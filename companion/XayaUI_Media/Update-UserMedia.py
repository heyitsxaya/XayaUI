#!/usr/bin/env python3
"""Scan Graphics/, Icons/ and Sounds/ next to this script and rewrite UserMedia.lua. Standard library only."""
import os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PIC_EXT = {".png", ".tga", ".blp", ".jpg", ".jpeg"}
SND_EXT = {".ogg", ".mp3"}
warnings = []

def pow2(n): return n > 0 and (n & (n - 1)) == 0

def size_png(b):
    if b[:8] != b"\x89PNG\r\n\x1a\n" or b[12:16] != b"IHDR": return None
    return struct.unpack(">II", b[16:24])

def size_tga(b):
    if len(b) < 18: return None
    itype, w, h, bpp = b[2], struct.unpack("<H", b[12:14])[0], struct.unpack("<H", b[14:16])[0], b[16]
    if itype not in (2, 3, 10, 11): warnings.append("color-mapped TGA (type %d)" % itype)
    elif bpp not in (8, 24, 32): warnings.append("TGA is %d bits per pixel (the game accepts 8, 24 or 32)" % bpp)
    return (w, h)

def size_blp(b):
    if b[:4] not in (b"BLP2", b"BLP1") or len(b) < 20: return None
    return struct.unpack("<II", b[12:20])

def size_jpg(b):
    if b[:2] != b"\xff\xd8": return None
    i = 2
    while i + 9 < len(b):
        if b[i] != 0xFF: i += 1; continue
        m = b[i + 1]
        if m in (0xC0, 0xC1, 0xC2): return struct.unpack(">HH", b[i + 7:i + 9])[::-1]
        if m in (0xD8, 0x01) or 0xD0 <= m <= 0xD7: i += 2; continue
        i += 2 + struct.unpack(">H", b[i + 2:i + 4])[0]
    return None

READERS = {".png": size_png, ".tga": size_tga, ".blp": size_blp, ".jpg": size_jpg, ".jpeg": size_jpg}

def lua(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def scan(folder, exts):
    root = os.path.join(HERE, folder)
    out = []
    if not os.path.isdir(root): return out
    for dp, dn, fn in os.walk(root):
        dn.sort()
        for f in sorted(fn):
            ext = os.path.splitext(f)[1].lower()
            if ext in exts:
                rel = os.path.relpath(os.path.join(dp, f), HERE).replace(os.sep, "/")
                out.append((rel, os.path.join(dp, f), ext))
    return out

def main():
    gl, sl = [], []
    for folder, kind in (("Graphics", "texture"), ("Icons", "icon")):
        for rel, full, ext in scan(folder, PIC_EXT):
            del warnings[:]
            with open(full, "rb") as fh: head = fh.read(65536)
            dims = READERS[ext](head)
            if not dims:
                print("SKIP  %s: could not read the picture header (corrupt or not really a %s)" % (rel, ext)); continue
            w, h = dims
            if not (pow2(w) and pow2(h)): warnings.append("%dx%d is not a power of two, the game may draw it blank" % (w, h))
            if " " in rel: warnings.append("space in the file name")
            if kind == "icon" and (w != h or w > 200 or h > 200):
                print("SKIP  %s: icons must be square and at most 200x200 pixels (this one is %dx%d); resize it and run this again" % (rel, w, h)); continue
            for m in warnings: print("WARN  %s: %s" % (rel, m))
            label = os.path.splitext(os.path.basename(rel))[0]
            gl.append('        { %s, %s, %d, %d, %s },' % (lua(label), lua(rel), w, h, lua(kind)))
    for rel, full, ext in scan("Sounds", SND_EXT):
        label = os.path.splitext(os.path.basename(rel))[0]
        sl.append('        { %s, %s },' % (lua(label), lua(rel)))
    text = ("-- Generated by Update-UserMedia.py. Safe to edit by hand; the script overwrites this file. See README.txt.\n"
            "-- Paths are relative to this addon's folder. graphics: { label, file, width, height, kind }  sounds: { label, file }\n"
            "XayaUI_UserMedia = {\n    graphics = {\n" + "\n".join(gl) + ("\n" if gl else "") + "    },\n    sounds = {\n" + "\n".join(sl) + ("\n" if sl else "") + "    },\n}\n")
    with open(os.path.join(HERE, "UserMedia.lua"), "w", encoding="utf-8", newline="\n") as fh: fh.write(text)
    print("UserMedia.lua written: %d pictures, %d sounds. Now /reload in game." % (len(gl), len(sl)))
    if os.name == "nt" and sys.stdin and sys.stdin.isatty() is False: pass

if __name__ == "__main__":
    main()
